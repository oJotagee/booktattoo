import { describe, expect, it } from 'bun:test';

import {
  buildBlockedTimes,
  dayRange,
  isSlotSequenceAvailable,
  isValidDate,
  monthRange,
  requiredSlots,
  toScheduledAt,
  toSlotTime,
  toStudioDate,
} from '@/domain/schedule';

const TIMES = ['09:00', '09:30', '10:00', '10:30', '11:00', '14:00', '14:30'];

describe('schedule', () => {
  describe('requiredSlots', () => {
    it('rounds the duration up to 30 minute slots', () => {
      expect(requiredSlots(30)).toBe(1);
      expect(requiredSlots(45)).toBe(2);
      expect(requiredSlots(120)).toBe(4);
    });

    it('always needs at least one slot', () => {
      expect(requiredSlots(0)).toBe(1);
    });
  });

  describe('buildBlockedTimes', () => {
    it('blocks every slot covered by the appointment duration', () => {
      expect(buildBlockedTimes([{ time: '09:30', duration: 90 }], TIMES)).toEqual([
        '09:30',
        '10:00',
        '10:30',
      ]);
    });

    it('follows the order of the artist times across gaps', () => {
      expect(buildBlockedTimes([{ time: '11:00', duration: 60 }], TIMES)).toEqual([
        '11:00',
        '14:00',
      ]);
    });

    it('still blocks a start time that is no longer in the artist times', () => {
      expect(buildBlockedTimes([{ time: '08:00', duration: 60 }], TIMES)).toEqual(['08:00']);
    });
  });

  describe('isSlotSequenceAvailable', () => {
    it('accepts a free sequence', () => {
      expect(isSlotSequenceAvailable('09:00', 2, TIMES, ['10:00'])).toBe(true);
    });

    it('rejects a sequence that hits a blocked slot', () => {
      expect(isSlotSequenceAvailable('09:30', 2, TIMES, ['10:00'])).toBe(false);
    });

    it('rejects a sequence that runs past the last slot of the day', () => {
      expect(isSlotSequenceAvailable('14:30', 2, TIMES, [])).toBe(false);
    });

    it('rejects a start time outside the artist times', () => {
      expect(isSlotSequenceAvailable('12:00', 1, TIMES, [])).toBe(false);
    });
  });

  describe('dates in the studio time zone', () => {
    it('validates real calendar dates', () => {
      expect(isValidDate('2026-10-16')).toBe(true);
      expect(isValidDate('2026-02-30')).toBe(false);
      expect(isValidDate('16/10/2026')).toBe(false);
    });

    it('builds the day range at São Paulo midnight', () => {
      expect(dayRange('2026-10-16')).toEqual({
        start: new Date('2026-10-16T03:00:00.000Z'),
        end: new Date('2026-10-17T03:00:00.000Z'),
      });
    });

    it('converts date and time to an instant and back', () => {
      const scheduledAt = toScheduledAt('2026-10-16', '10:30');

      expect(scheduledAt).toEqual(new Date('2026-10-16T13:30:00.000Z'));
      expect(toSlotTime(scheduledAt, '2026-10-16')).toBe('10:30');
    });

    it('supports the 24:00 and 24:30 slots generated by the profile', () => {
      const scheduledAt = toScheduledAt('2026-10-16', '24:30');

      expect(scheduledAt).toEqual(new Date('2026-10-17T03:30:00.000Z'));
      expect(toSlotTime(scheduledAt, '2026-10-16')).toBe('24:30');
    });

    it('uses the studio date late in the evening', () => {
      expect(toStudioDate(new Date('2026-10-17T01:00:00.000Z'))).toBe('2026-10-16');
    });

    it('builds the month range, including the year turn', () => {
      expect(monthRange(new Date('2026-12-20T12:00:00.000Z'))).toEqual({
        start: new Date('2026-12-01T03:00:00.000Z'),
        end: new Date('2027-01-01T03:00:00.000Z'),
      });
    });
  });
});
